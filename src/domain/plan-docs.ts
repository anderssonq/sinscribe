const BODY_START = "<!-- sinscribe:body:start -->";
const BODY_END = "<!-- sinscribe:body:end -->";

const NAV_ORDER: { id: PlanFileId; label: string }[] = [
  { id: "index", label: "Index" },
  { id: "requirements", label: "Requirements" },
  { id: "design", label: "Design" },
  { id: "tasks", label: "Tasks" },
  { id: "handoff", label: "Handoff" },
  { id: "loop", label: "Loop prompt" },
];

/** One-line cross-reference bar; the current document is bold, not linked. */
export function buildNavLine(current: PlanFileId): string {
  return NAV_ORDER.map(({ id, label }) =>
    id === current ? `**${label}**` : `[${label}](${PLAN_FILES[id]})`,
  ).join(" · ");
}

export type PlanDocInput = {
  stage: PlanStageId;
  branch: string;
  feature: string;
  body: string;
  /** Injectable for deterministic tests; defaults to now. */
  generatedAt?: Date;
};

/** The external formats a plan document follows (src/standards/registry.ts). */
const PLAN_STANDARDS = [formatStamp("ears-spec"), formatStamp("spec-kit")].join(
  ", ",
);

/**
 * Frames a model-written body: metadata comments, title and nav are added
 * here (the model cannot know the date and must not invent links), and the
 * body is fenced by markers so its hash ignores the framing.
 */
export function buildPlanDocMarkdown(input: PlanDocInput): string {
  const generatedAt = (input.generatedAt ?? new Date()).toISOString();
  const nav = buildNavLine(input.stage);

  return [
    `<!-- Generated by ${CLI_DISPLAY_NAME} v${SINSCRIBE_VERSION} on ${generatedAt} · standards: ${PLAN_STANDARDS} -->`,
    `<!-- sinscribe-plan-doc: ${input.stage} · Branch: ${input.branch} -->`,
    "",
    `# ${STAGE_TITLES[input.stage]} — ${firstLine(input.feature)}`,
    "",
    `> ${nav}`,
    "",
    BODY_START,
    input.body.trim(),
    BODY_END,
    "",
    "---",
    "",
    `${nav}`,
    "",
  ].join("\n");
}

/**
 * The editable body of a plan document. Uses the markers when present; a
 * file whose markers were deleted by hand falls back to "everything after
 * the leading comments, title and nav", so a human edit never loses content.
 */
export function extractPlanDocBody(raw: string): string {
  const text = raw.replace(/\r\n/gu, "\n");
  const start = text.indexOf(BODY_START);
  const end = text.indexOf(BODY_END);

  if (start !== -1 && end > start) {
    return text.slice(start + BODY_START.length, end).trim();
  }

  const lines = text.split("\n");
  let index = 0;

  while (
    index < lines.length &&
    (lines[index].trim().length === 0 ||
      /^<!--.*-->$/u.test(lines[index].trim()) ||
      /^# /u.test(lines[index]) ||
      /^> .*\]\(index\.md\)/u.test(lines[index]))
  ) {
    index += 1;
  }

  return lines.slice(index).join("\n").trim();
}

/**
 * A short content hash of a stage body. Task checkboxes are normalised
 * before hashing: an agent ticking `[x]` is progress, not a spec change, and
 * must not make the handoff stale or flag tasks.md as hand-edited.
 */
export function hashDoc(stage: PlanStageId, body: string): string {
  let normalised = body.replace(/\r\n/gu, "\n").trim();

  if (stage === "tasks") {
    normalised = normalised.replace(/^(\s*[-*]\s+)\[[xX]\]/gmu, "$1[ ]");
  }

  return createHash("sha256").update(normalised).digest("hex").slice(0, 12);
}

function firstLine(text: string): string {
  const line = text.trim().split("\n")[0]?.trim() ?? "";

  return line.length > 80 ? `${line.slice(0, 77)}...` : line || "Spec plan";
}

