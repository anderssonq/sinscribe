export function buildIndexMarkdown(input: {
  index: PlanIndex;
  views: Record<PlanStageId, StageView>;
  progress: ProgressReport | null;
  coverage: CoverageReport | null;
  dirRel: string;
  generatedAt?: Date;
}): string {
  const { index, views, progress, coverage, dirRel } = input;
  const generatedAt = (input.generatedAt ?? new Date()).toISOString();
  const rows = PLAN_STAGES.map((stage, position) => {
    const view = views[stage];
    const record = index.stages[stage];
    const status =
      view.status === "stale"
        ? `stale (${view.staleBecause ?? "upstream changed"})`
        : view.editedSinceApproval
          ? "approved · edited since"
          : view.status;

    return (
      `| ${position + 1} | ${STAGE_TITLES[stage]} | ` +
      `[${PLAN_FILES[stage]}](${PLAN_FILES[stage]}) | ${status} | ` +
      `${record?.approvedAt?.slice(0, 10) ?? "—"} | ${record?.mode ?? "—"} |`
    );
  });
  const progressLines =
    progress === null || progress.total === 0
      ? ["_Tasks are not approved yet._"]
      : [
          `- ${summarizeProgress(progress)}`,
          ...(coverage && coverage.uncoveredAcs.length > 0
            ? [`- Uncovered: ${coverage.uncoveredAcs.join(", ")}`]
            : []),
          ...progress.inconsistencies
            .slice(0, 5)
            .map((issue) => `- ⚠ ${issue}`),
        ];

  return [
    `<!-- Generated by ${CLI_DISPLAY_NAME} v${SINSCRIBE_VERSION} on ${generatedAt} -->`,
    // ">" only occurs inside JSON strings, and \u003e parses back to it, so a
    // feature such as "a }--> b" cannot end the comment early.
    `<!-- sinscribe-plan: ${JSON.stringify(index).replace(/>/gu, "\\u003e")} -->`,
    "<!-- Written by Sinscribe only. Edit the stage files, not this one. -->",
    "",
    `# ${firstLine(index.feature)} — Spec plan`,
    "",
    `> ${buildNavLine("index")}`,
    "",
    `Branch \`${index.branch}\` · Ticket ${index.ticket ?? "none"} · ` +
      `Base ${index.baseRef ? `\`${index.baseRef}\`` : "unknown"}`,
    "",
    "## Stages",
    "",
    "| # | Stage | File | Status | Approved | Context |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
    "## Progress",
    "",
    ...progressLines,
    "",
    "## How to resume",
    "",
    "- Humans: run `sinscribe plan` (menu → Spec plan) to continue, regenerate a stage, or sync progress.",
    `- Coding agents: start at [${PLAN_FILES.loop}](${PLAN_FILES.loop}) — or \`sinscribe plan --loop-prompt\`.`,
    "- After commits land: `sinscribe plan --sync` refreshes the status here and in handoff.md.",
    "",
    "## Loop contract",
    "",
    "1. One task at a time, in dependency order — the first unchecked task whose dependencies are checked.",
    "2. A task is done only when its Verify command passes; then tick it and — unless the project's rules forbid commits — commit it with `[T-n]` in the subject.",
    "3. Every task appends an entry to the handoff log.",
    "4. Requirements and design are never edited by the agent — it records a spec delta and stops.",
    "5. Stop at checkpoints, on blockers, and after three failed attempts.",
    "6. Finished means every task is checked **and** every AC is verified.",
    "",
    `<!-- Plan directory: ${dirRel} -->`,
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// loop-prompt.md — the operating contract for the coding agent
// ---------------------------------------------------------------------------

export function buildLoopPrompt(input: {
  dirRel: string;
  branch: string;
  feature: string;
  generatedAt?: Date;
}): string {
  const generatedAt = (input.generatedAt ?? new Date()).toISOString();
  const dir = input.dirRel;

  return [
    `<!-- Generated by ${CLI_DISPLAY_NAME} v${SINSCRIBE_VERSION} on ${generatedAt} -->`,
    `<!-- sinscribe-plan-doc: loop · Branch: ${input.branch} -->`,
    "",
    `# Implementation loop — ${firstLine(input.feature)}`,
    "",
    `> ${buildNavLine("loop")}`,
    "",
    `You are implementing an approved spec plan on branch \`${input.branch}\`.`,
    `The plan lives in \`${dir}/\`. The files are the source of truth — not this`,
    "conversation, not your memory of a previous session.",
    "",
    "## 0. Orient (every time you start or resume)",
    "",
    `1. Read, in order: \`${dir}/index.md\`, \`${dir}/requirements.md\`,`,
    `   \`${dir}/design.md\`, \`${dir}/tasks.md\`, \`${dir}/handoff.md\`.`,
    "2. Run `git status` and `git log --oneline -15`. If the working tree has",
    "   changes that no task explains, stop and ask before touching anything.",
    "3. Read the project's own rules (CLAUDE.md, AGENTS.md, CONTRIBUTING) and use",
    "   its real commands — never assume `npm test`.",
    "4. If index.md shows any stage as stale or not approved, stop: the plan",
    "   must be re-approved in Sinscribe (`sinscribe plan`) before you build.",
    "",
    "## 1. The loop",
    "",
    "Repeat until every task in tasks.md is checked:",
    "",
    "1. **Pick** the first unchecked `T-n` whose `Depends on` tasks are all checked.",
    "   Write it under `## Current task` in handoff.md.",
    "2. **Plan** in at most three lines: the files you will touch and how you",
    "   will prove it works. Touch only the task's `Files` unless the task is",
    "   impossible without another file — then say so in the log.",
    "3. **Test first** where the stack allows: write or extend a test for the",
    "   task's Acceptance and the ACs it Implements; see it fail.",
    "4. **Implement** the minimum that makes it pass. No drive-by refactors.",
    "5. **Verify**: run the task's exact `Verify` command, then the project's",
    "   broader test/build/lint gates. Read the output; do not assume.",
    "6. **On pass**: tick the task `[x]` in tasks.md and append a `## Log` entry",
    "   to handoff.md (changed · verify command → result · commit · notes). Then",
    "   commit: stage only the files this task touched plus tasks.md/handoff.md",
    "   (never `git add -A`), with `[T-n]` in the subject. **If the project's or",
    "   user's rules say not to commit, do not commit** — leave the change in the",
    "   working tree and write `Commit: uncommitted` in the log entry.",
    "7. **On fail**: diagnose the root cause and retry — at most three attempts.",
    "   Then record it under `## Blockers` in handoff.md and **stop**.",
    "8. **Checkpoint**: when you reach an unchecked `- [ ] Checkpoint` line, run",
    "   the full gates, summarise progress, and **stop** for human review. The",
    "   human ticks the checkpoint.",
    "",
    "## 2. Feedback into the spec (never edit it silently)",
    "",
    "- requirements.md and design.md are **read-only** for you.",
    "- If the code contradicts the design, a requirement is ambiguous, or a",
    "  needed decision is not covered: write it under `## Spec deltas` in",
    "  handoff.md (what, why, options A/B/C, your recommendation) and **stop**.",
    "  The human updates the spec in Sinscribe; regenerated tasks keep their ids",
    "  and checkmarks.",
    "- Things you notice outside the task's scope go under",
    "  `## Noticed but not touching` — do not fix them now.",
    "",
    "## 3. Finish",
    "",
    "When every task is checked:",
    "",
    "1. Walk every `AC-n.m` in requirements.md. For each, cite the test or the",
    "   command that proves it, and run it. Record the results in the log as",
    "   `### AC verification`.",
    "2. Any AC you cannot prove is not done. Do **not** add tasks to tasks.md",
    "   yourself — any edit beyond a checkbox makes the plan stale. Write it under",
    "   `## Spec deltas` in handoff.md (the AC, why it is unproven, the task you",
    "   propose) and stop; the human regenerates tasks in Sinscribe.",
    "3. Finish with a summary: tasks completed, commits, tests added, open spec",
    "   deltas, and anything left for the human. Then tell the human to run",
    "   `sinscribe plan --sync`.",
    "",
    "## Stop conditions — stop and report instead of pushing on",
    "",
    "- A Verify command fails three times, or the build breaks with no obvious fix.",
    "- A task needs a decision the spec does not cover (→ spec delta).",
    "- An unchecked checkpoint is reached.",
    "- The change is risky or irreversible: auth/permissions, data migrations,",
    "  deletions, payments, secrets, deploys — get explicit sign-off first.",
    "- Unexplained local changes, or the plan is stale.",
    "",
    "## Red flags — if you catch yourself thinking these, stop",
    "",
    "| Thought | Reality |",
    "| --- | --- |",
    '| "This test is flaky, I\'ll skip it" | A skipped check is an unverified task. Record a blocker. |',
    '| "I\'ll tick it now and verify later" | Done means verified. Unverified work is not done. |',
    "| \"While I'm here I'll also fix…\" | Scope creep. Log it under Noticed but not touching. |",
    '| "The spec is obviously wrong, I\'ll adjust it" | Write a spec delta and stop. The human owns the spec. |',
    '| "I\'ll batch these three tasks into one commit" | One task, one commit — every point stays revertable (when committing is allowed). |',
    '| "It passed before, no need to re-run" | Re-run when the code has moved since. |',
    "",
  ].join("\n");
}
