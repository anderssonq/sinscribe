export type PlanStageRecord = {
  status: "draft" | "approved";
  generatedAt: string;
  approvedAt: string | null;
  /** hashDoc of the body when it was last written or approved. */
  sha: string;
  /** hashDoc of the upstream body this stage was generated against. */
  upstreamSha: string | null;
  /** How the model gathered context: explored the repo, or single-shot. */
  mode: string;
  model: string;
};

export type PlanIndex = {
  version: 1;
  branch: string;
  feature: string;
  ticket: string | null;
  baseRef: string | null;
  createdAt: string;
  updatedAt: string;
  stages: Partial<Record<PlanStageId, PlanStageRecord>>;
};

export type StageStatus = "missing" | "draft" | "approved" | "stale";

export type StageView = {
  status: StageStatus;
  /** Approved, but the file on disk no longer matches what was approved. */
  editedSinceApproval: boolean;
  staleBecause: string | null;
};

const INDEX_STATE_PATTERN = /<!--\s*sinscribe-plan:\s*(\{[\s\S]*?\})\s*-->/u;

/** Reads only the JSON state comment; a hand-edited table cannot corrupt it. */
export function parseIndex(raw: string): PlanIndex | null {
  const match = INDEX_STATE_PATTERN.exec(raw);

  if (!match) {
    return null;
  }

  let value: unknown;

  try {
    value = JSON.parse(match[1]);
  } catch {
    return null;
  }

  return isPlanIndex(value) ? value : null;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isNullableString(value: unknown): value is string | null {
  return value === null || typeof value === "string";
}

function isStageRecord(value: unknown): value is PlanStageRecord {
  return (
    isRecord(value) &&
    (value.status === "draft" || value.status === "approved") &&
    typeof value.generatedAt === "string" &&
    isNullableString(value.approvedAt) &&
    typeof value.sha === "string" &&
    isNullableString(value.upstreamSha) &&
    typeof value.mode === "string" &&
    typeof value.model === "string"
  );
}

function isPlanIndex(value: unknown): value is PlanIndex {
  if (
    !isRecord(value) ||
    value.version !== 1 ||
    typeof value.branch !== "string" ||
    typeof value.feature !== "string" ||
    !isNullableString(value.ticket) ||
    !isNullableString(value.baseRef) ||
    typeof value.createdAt !== "string" ||
    typeof value.updatedAt !== "string" ||
    !isRecord(value.stages)
  ) {
    return false;
  }

  return Object.entries(value.stages).every(
    ([stage, record]) => isPlanStage(stage) && isStageRecord(record),
  );
}

/**
 * Derives each stage's status from the index records and the bodies on
 * disk. Nothing here is stored: staleness is recomputed from hashes on every
 * read, so a hand edit or a regenerated upstream is always noticed.
 */
export function computeStageViews(
  index: PlanIndex | null,
  bodies: Partial<Record<PlanStageId, string>>,
): Record<PlanStageId, StageView> {
  const views = {} as Record<PlanStageId, StageView>;

  for (const stage of PLAN_STAGES) {
    const record = index?.stages[stage];
    const body = bodies[stage];

    if (!record || body === undefined) {
      views[stage] = {
        status: "missing",
        editedSinceApproval: false,
        staleBecause: null,
      };
      continue;
    }

    // The handoff is a living log the coding agent appends to by design.
    const editedSinceApproval =
      record.status === "approved" &&
      stage !== "handoff" &&
      hashDoc(stage, body) !== record.sha;
    const staleBecause = upstreamProblem(stage, record, bodies, views);

    views[stage] = {
      status:
        staleBecause !== null
          ? "stale"
          : record.status === "approved"
            ? "approved"
            : "draft",
      editedSinceApproval,
      staleBecause,
    };
  }

  return views;
}

function upstreamProblem(
  stage: PlanStageId,
  record: PlanStageRecord,
  bodies: Partial<Record<PlanStageId, string>>,
  views: Record<PlanStageId, StageView>,
): string | null {
  const upstream = UPSTREAM[stage];

  if (upstream === null) {
    return null;
  }

  const upstreamView = views[upstream];
  const upstreamBody = bodies[upstream];
  const upstreamFile = PLAN_FILES[upstream];

  if (upstreamView.status !== "approved" || upstreamBody === undefined) {
    return `${upstreamFile} is not approved`;
  }

  if (upstreamView.editedSinceApproval) {
    return `${upstreamFile} was edited after approval`;
  }

  if (record.upstreamSha !== hashDoc(upstream, upstreamBody)) {
    return `${upstreamFile} changed since this was generated`;
  }

  return null;
}

/** The first stage that still needs work, in pipeline order. */
export function nextStage(
  views: Record<PlanStageId, StageView>,
): PlanStageId | null {
  return (
    PLAN_STAGES.find(
      (stage) =>
        views[stage].status !== "approved" || views[stage].editedSinceApproval,
    ) ?? null
  );
}

