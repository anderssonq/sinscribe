import { createHash } from "node:crypto";
import path from "node:path";
import {
  CLI_DISPLAY_NAME,
  SINSCRIBE_DIRNAME,
  SINSCRIBE_VERSION,
} from "../constants.js";
import { sanitizeBranchKey } from "../session/store.js";
import { formatStamp } from "../standards/registry.js";

/**
 * The spec plan's pure core: file layout, document framing, hashing and
 * staleness, the requirement/task parsers, coverage and progress. No I/O and
 * no model calls — everything that decides whether a plan is consistent is
 * deterministic and unit-tested here, so the LLM only ever writes prose.
 *
 * The files are the source of truth. Approval lives in index.md (written only
 * by code), never in a conversation or the session JSON: a fresh session, a
 * different agent, or a human reading the repo sees the same state.
 */

export const PLAN_STAGES = [
  "requirements",
  "design",
  "tasks",
  "handoff",
] as const;

export type PlanStageId = (typeof PLAN_STAGES)[number];

export const PLAN_FILES = {
  requirements: "requirements.md",
  design: "design.md",
  tasks: "tasks.md",
  handoff: "handoff.md",
  index: "index.md",
  loop: "loop-prompt.md",
} as const;

export type PlanFileId = keyof typeof PLAN_FILES;

export const STAGE_TITLES: Record<PlanStageId, string> = {
  requirements: "Requirements",
  design: "Design",
  tasks: "Tasks",
  handoff: "Handoff",
};

/**
 * The approved document each stage is generated from. Staleness keys only on
 * the direct upstream: a requirements change makes design stale, which makes
 * tasks stale in turn, so the chain is transitively covered.
 */
export const UPSTREAM: Record<PlanStageId, PlanStageId | null> = {
  requirements: null,
  design: "requirements",
  tasks: "design",
  handoff: "tasks",
};

/** Plans live in .sinscribe/specs/; releases before that used ./specs/. */
export const PLAN_ROOT_DIRNAME = "specs";

export function isPlanStage(value: string): value is PlanStageId {
  return (PLAN_STAGES as readonly string[]).includes(value);
}

/** Repo-relative plan directory, e.g. `.sinscribe/specs/feat-login`. */
export function getPlanDirRel(branch: string): string {
  return `${SINSCRIBE_DIRNAME}/${PLAN_ROOT_DIRNAME}/${sanitizeBranchKey(branch)}`;
}

export function getPlanDir(repoRoot: string, branch: string): string {
  return path.join(repoRoot, ...getPlanDirRel(branch).split("/"));
}

/** Repo-relative pre-.sinscribe/ plan directory, e.g. `specs/feat-login`. */
export function getLegacyPlanDirRel(branch: string): string {
  return `${PLAN_ROOT_DIRNAME}/${sanitizeBranchKey(branch)}`;
}

