export type AcceptanceCriterion = { id: string; text: string };

export type Requirement = {
  id: string;
  title: string;
  acs: AcceptanceCriterion[];
};

const REQ_HEADING = /^#{2,4}\s+\**\s*(REQ-\d+)\s*\**\s*[:—–-]?\s*\**\s*(.*)$/u;
const AC_LINE =
  /^\s*[-*]\s+(?:\[[ xX]\]\s+)?\**\s*(AC-\d+(?:\.\d+)?)\s*\**\s*[:—–-]?\s*\**\s*(.*)$/u;

/** `### REQ-n: title` headings, each followed by `- AC-n.m: text` bullets. */
export function parseRequirements(markdown: string): Requirement[] {
  const requirements: Requirement[] = [];
  let current: Requirement | null = null;

  for (const line of markdown.replace(/\r\n/gu, "\n").split("\n")) {
    const heading = REQ_HEADING.exec(line);

    if (heading) {
      current = { id: heading[1], title: cleanText(heading[2]), acs: [] };
      requirements.push(current);
      continue;
    }

    // A new non-REQ heading of the same depth ends the requirement block.
    if (/^#{1,3}\s/u.test(line)) {
      current = null;
      continue;
    }

    const ac = AC_LINE.exec(line);

    if (ac && current) {
      current.acs.push({ id: ac[1], text: cleanText(ac[2]) });
    }
  }

  return requirements;
}

export type TaskSize = "XS" | "S" | "M" | "L" | "XL";

export type PlanTask = {
  id: string;
  title: string;
  done: boolean;
  implements: string[];
  dependsOn: string[];
  files: string[];
  acceptance: string | null;
  verify: string | null;
  size: TaskSize | null;
  /** 0-based line index of the checkbox line in tasks.md. */
  line: number;
};

const TASK_LINE =
  /^\s*[-*]\s+\[([ xX])\]\s+\**\s*(T-\d+)\s*\**\s*[:—–-]?\s*\**\s*(.*)$/u;
const CHECKPOINT_LINE = /^\s*[-*]\s+\[([ xX])\]\s+\**\s*Checkpoint\b/iu;
const FIELD_LINE = /^\s+[-*]\s+\**\s*([A-Za-z ]+?)\s*\**\s*:\s*\**\s*(.*)$/u;
const AC_ID = /\bAC-\d+(?:\.\d+)?\b/gu;
const TASK_ID = /\bT-\d+\b/gu;
/** The loop's commit convention: `[T-n]` in the subject, nothing looser. */
const COMMIT_TASK_ID = /\[(T-\d+)\]/gu;

/**
 * `- [ ] T-n: title` lines with indented `- Field: value` sub-bullets.
 * Tolerant of bold markers and `[X]`, because an external agent edits this
 * file and small formatting drift must not lose its progress.
 */
export function parseTasks(markdown: string): PlanTask[] {
  const tasks: PlanTask[] = [];
  let current: PlanTask | null = null;
  const lines = markdown.replace(/\r\n/gu, "\n").split("\n");

  lines.forEach((line, lineIndex) => {
    const task = TASK_LINE.exec(line);

    if (task) {
      current = {
        id: task[2],
        title: cleanText(task[3]),
        done: task[1] !== " ",
        implements: [],
        dependsOn: [],
        files: [],
        acceptance: null,
        verify: null,
        size: null,
        line: lineIndex,
      };
      tasks.push(current);
      return;
    }

    if (CHECKPOINT_LINE.test(line) || /^\S/u.test(line)) {
      current = null;
      return;
    }

    const field = FIELD_LINE.exec(line);

    if (field && current) {
      applyTaskField(current, field[1].toLowerCase(), field[2]);
    }
  });

  return tasks;
}

function applyTaskField(task: PlanTask, name: string, value: string): void {
  const text = cleanText(value);

  if (name.startsWith("implement")) {
    task.implements = unique(text.match(AC_ID) ?? []);
  } else if (name.startsWith("depend")) {
    task.dependsOn = unique(text.match(TASK_ID) ?? []);
  } else if (name.startsWith("file")) {
    task.files = text
      .split(",")
      .map((file) => file.replace(/`/gu, "").trim())
      .filter((file) => file.length > 0 && !/^none$/iu.test(file));
  } else if (name.startsWith("acceptance")) {
    task.acceptance = text || null;
  } else if (name.startsWith("verify")) {
    task.verify = text.replace(/^`+|`+$/gu, "").trim() || null;
  } else if (name.startsWith("size")) {
    const size = /\b(XL|XS|S|M|L)\b/u.exec(text.toUpperCase());

    task.size = size ? (size[1] as TaskSize) : null;
  }
}

/** Checkpoint lines in tasks.md: `- [ ] Checkpoint: …`. */
export function countCheckpoints(markdown: string): {
  total: number;
  done: number;
} {
  let total = 0;
  let done = 0;

  for (const line of markdown.split("\n")) {
    const match = CHECKPOINT_LINE.exec(line);

    if (match) {
      total += 1;
      done += match[1] === " " ? 0 : 1;
    }
  }

  return { total, done };
}

function cleanText(text: string): string {
  return text.replace(/\*\*/gu, "").trim();
}

function unique(values: string[]): string[] {
  return [...new Set(values)];
}

