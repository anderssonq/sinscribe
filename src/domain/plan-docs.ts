// Coverage — the traceability check agent-skills leaves to prose
// ---------------------------------------------------------------------------

/** Tasks touching more files than this should be split (agent-skills' M). */
export const MAX_TASK_FILES = 5;

export type CoverageReport = {
  /** Block approval: the plan references things that do not exist. */
  errors: string[];
  /** Shown and recorded, but approval is allowed. */
  warnings: string[];
  uncoveredAcs: string[];
  totalAcs: number;
};

export function computeCoverage(
  requirements: Requirement[],
  tasks: PlanTask[],
): CoverageReport {
  const errors: string[] = [];
  const warnings: string[] = [];
  const acIds = requirements.flatMap((req) => req.acs.map((ac) => ac.id));
  const knownAcs = new Set(acIds);
  const taskIds = new Set<string>();

  for (const id of duplicates(acIds)) {
    errors.push(`${id} is defined more than once in requirements.md`);
  }

  for (const id of duplicates(tasks.map((task) => task.id))) {
    errors.push(`${id} is defined more than once in tasks.md`);
  }

  for (const task of tasks) {
    taskIds.add(task.id);
  }

  if (acIds.length === 0) {
    warnings.push("no AC-n.m acceptance criteria found in requirements.md");
  }

  if (tasks.length === 0) {
    errors.push("no `- [ ] T-n: …` tasks found in tasks.md");
  }

  const covered = new Set<string>();

  for (const task of tasks) {
    for (const ac of task.implements) {
      if (knownAcs.has(ac)) {
        covered.add(ac);
      } else {
        errors.push(`${task.id} implements ${ac}, which requirements.md lacks`);
      }
    }

    for (const dep of task.dependsOn) {
      if (!taskIds.has(dep)) {
        errors.push(`${task.id} depends on ${dep}, which does not exist`);
      } else if (dep === task.id) {
        errors.push(`${task.id} depends on itself`);
      }
    }

    if (task.implements.length === 0) {
      warnings.push(`${task.id} does not name the AC it implements`);
    }

    if (task.verify === null) {
      warnings.push(`${task.id} has no Verify command`);
    }

    if (
      task.size === "L" ||
      task.size === "XL" ||
      task.files.length > MAX_TASK_FILES
    ) {
      warnings.push(
        `${task.id} is too large (${task.size ?? `${task.files.length} files`}) — split it`,
      );
    }
  }

  for (const cycle of findCycles(tasks)) {
    errors.push(`dependency cycle: ${cycle.join(" → ")}`);
  }

  const uncoveredAcs = acIds.filter((id) => !covered.has(id));

  if (uncoveredAcs.length > 0) {
    warnings.push(`no task implements ${uncoveredAcs.join(", ")}`);
  }

  return {
    errors: unique(errors),
    warnings: unique(warnings),
    uncoveredAcs,
    totalAcs: acIds.length,
  };
}

function duplicates(values: string[]): string[] {
  const seen = new Set<string>();
  const repeated = new Set<string>();

  for (const value of values) {
    if (seen.has(value)) {
      repeated.add(value);
    }

    seen.add(value);
  }

  return [...repeated];
}

function findCycles(tasks: PlanTask[]): string[][] {
  // Duplicate ids (already an error) merge their edges rather than hiding them.
  const deps = new Map<string, string[]>();

  for (const task of tasks) {
    deps.set(task.id, [...(deps.get(task.id) ?? []), ...task.dependsOn]);
  }
  const state = new Map<string, "visiting" | "done">();
  const cycles: string[][] = [];

  const visit = (id: string, trail: string[]): void => {
    if (state.get(id) === "done") {
      return;
    }

    if (state.get(id) === "visiting") {
      cycles.push([...trail.slice(trail.indexOf(id)), id]);
      return;
    }

    state.set(id, "visiting");

    for (const dep of deps.get(id) ?? []) {
      if (deps.has(dep) && dep !== id) {
        visit(dep, [...trail, id]);
      }
    }

    state.set(id, "done");
  };

  for (const task of tasks) {
    visit(task.id, []);
  }

  return cycles;
}

/**
 * Re-applies `[x]` to regenerated tasks that keep their id, so revising the
 * plan mid-implementation does not erase progress. Done tasks that vanished
 * are reported: their work exists in git but no longer in the plan.
 */
export function preserveTaskState(
  previous: PlanTask[],
  nextMarkdown: string,
): { markdown: string; dropped: string[] } {
  const done = new Set(
    previous.filter((task) => task.done).map((task) => task.id),
  );
  const seen = new Set<string>();
  const markdown = nextMarkdown
    .split("\n")
    .map((line) => {
      const match = TASK_LINE.exec(line);

      if (!match) {
        return line;
      }

      seen.add(match[2]);

      return done.has(match[2]) ? line.replace(/\[[ xX]\]/u, "[x]") : line;
    })
    .join("\n");

  return { markdown, dropped: [...done].filter((id) => !seen.has(id)) };
}

