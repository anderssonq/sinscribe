// Progress — what the loop has actually done
// ---------------------------------------------------------------------------

export type AcState = "done" | "partial" | "uncovered" | "pending";

export type ProgressReport = {
  done: number;
  total: number;
  next: PlanTask | null;
  acs: { id: string; state: AcState }[];
  commitsByTask: Record<string, string[]>;
  /** Plan and git disagree — worth a human look. */
  inconsistencies: string[];
};

export function computeProgress(
  requirements: Requirement[],
  tasks: PlanTask[],
  commits: { sha: string; subject: string }[],
): ProgressReport {
  const byId = new Map(tasks.map((task) => [task.id, task]));
  const commitsByTask: Record<string, string[]> = {};
  const inconsistencies: string[] = [];

  for (const commit of commits) {
    const ids = [...commit.subject.matchAll(COMMIT_TASK_ID)].map(
      (match) => match[1],
    );

    for (const id of unique(ids)) {
      (commitsByTask[id] ??= []).push(commit.sha);
    }
  }

  for (const [id, shas] of Object.entries(commitsByTask)) {
    const task = byId.get(id);

    if (!task) {
      inconsistencies.push(`commit ${shas[0]} cites ${id}, not in tasks.md`);
    } else if (!task.done) {
      inconsistencies.push(
        `commit ${shas[0]} cites ${id}, but it is not checked`,
      );
    }
  }

  // Only a commit-based workflow expects a commit per task: when no commit
  // cites any task (e.g. the rules say "do not commit"), silence is normal.
  if (Object.keys(commitsByTask).length > 0) {
    for (const task of tasks) {
      if (task.done && !commitsByTask[task.id]) {
        inconsistencies.push(`${task.id} is checked but no commit cites it`);
      }
    }
  }

  const next =
    tasks.find(
      (task) =>
        !task.done &&
        task.dependsOn.every((dep) => byId.get(dep)?.done ?? true),
    ) ?? null;

  const acs = requirements.flatMap((req) =>
    req.acs.map((ac) => {
      const implementing = tasks.filter((task) =>
        task.implements.includes(ac.id),
      );
      const doneCount = implementing.filter((task) => task.done).length;
      const state: AcState =
        implementing.length === 0
          ? "uncovered"
          : doneCount === implementing.length
            ? "done"
            : doneCount > 0
              ? "partial"
              : "pending";

      return { id: ac.id, state };
    }),
  );

  return {
    done: tasks.filter((task) => task.done).length,
    total: tasks.length,
    next,
    acs,
    commitsByTask,
    inconsistencies,
  };
}

export function summarizeProgress(progress: ProgressReport): string {
  const acsDone = progress.acs.filter((ac) => ac.state === "done").length;
  const next = progress.next ? ` · next ${progress.next.id}` : "";

  return (
    `tasks ${progress.done}/${progress.total} · ` +
    `ACs ${acsDone}/${progress.acs.length} done${next}`
  );
}

// ---------------------------------------------------------------------------
// handoff.md — code-owned zones around the model's narrative
// ---------------------------------------------------------------------------

export const STATUS_ZONE_START = "<!-- sinscribe:status:start -->";
export const STATUS_ZONE_END = "<!-- sinscribe:status:end -->";
export const LOG_HEADING = "## Log";

const LOG_INTRO = [
  "<!-- Append-only. One entry per task, newest last:",
  "### <date> · T-n: <title>",
  "- Changed: <files and what changed>",
  "- Verify: `<command>` → <pass|fail + key output>",
  "- Commit: <sha>",
  "- Notes: <decisions, surprises, follow-ups> -->",
].join("\n");

/** The code-owned status zone at the top of handoff.md: one row per task. */
export function renderStatusZone(
  tasks: PlanTask[],
  progress: ProgressReport,
): string {
  const lines = [STATUS_ZONE_START, "## Status", ""];

  if (tasks.length === 0) {
    lines.push("_No tasks yet — approve tasks.md first._");
  } else {
    lines.push(`**${summarizeProgress(progress)}**`, "");
    lines.push("| Task | State | Commits |", "| --- | --- | --- |");

    for (const task of tasks) {
      const state = task.done
        ? "done"
        : progress.next?.id === task.id
          ? "**next**"
          : "todo";
      const commits = (progress.commitsByTask[task.id] ?? []).join(", ");

      lines.push(
        `| ${task.id}: ${task.title} | ${state} | ${commits || "—"} |`,
      );
    }
  }

  lines.push(STATUS_ZONE_END);

  return lines.join("\n");
}

/** Replaces the status zone; null when its markers are missing (refuse). */
export function replaceStatusZone(
  handoff: string,
  zone: string,
): string | null {
  const start = handoff.indexOf(STATUS_ZONE_START);
  const end = handoff.indexOf(STATUS_ZONE_END);

  if (start === -1 || end < start) {
    return null;
  }

  return (
    handoff.slice(0, start) + zone + handoff.slice(end + STATUS_ZONE_END.length)
  );
}

/** Everything from `## Log` to the end of the body; the log is never regenerated. */
export function extractLog(handoffBody: string): string | null {
  const match = /^## Log\s*$/mu.exec(handoffBody);

  return match ? handoffBody.slice(match.index).trim() : null;
}

/**
 * Assembles the handoff body: code-owned status zone, the model's narrative
 * (with any `## Log` it wrote dropped), then the preserved log — or a fresh
 * one with the entry template.
 */
export function assembleHandoffBody(input: {
  statusZone: string;
  narrative: string;
  previousLog: string | null;
}): string {
  const logStart = /^## Log\s*$/mu.exec(input.narrative)?.index;
  const narrative = input.narrative.slice(0, logStart).trim();
  const log = input.previousLog ?? `${LOG_HEADING}\n\n${LOG_INTRO}`;

  return [input.statusZone, "", narrative, "", log].join("\n").trim();
}

